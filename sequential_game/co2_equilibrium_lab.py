"""Small-game equilibrium diagnostics for the CO2 storage game.

This module deliberately separates game-theory diagnostics from the physical
transition kernel.  Supply a payoff tensor generated by the CO2 solver or by a
surrogate planner and use the same action labels to compare them.  For two
operators, payoff arrays have shape ``(n_actions_op0, n_actions_op1, 2)``.

The learning rules here are diagnostics for a finite normal-form game at one
state.  Applying them repeatedly at visited reservoir states gives a
state-conditioned, myopic Markov policy experiment; it is not by itself a
finite-horizon Markov-perfect equilibrium proof.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

import numpy as np


def make_placement_action_set(
    operator: int,
    candidate_cells: Sequence[tuple[int, int]],
    rates_m3_s: Sequence[float],
    *,
    prefix: str | None = None,
) -> list[Any]:
    """Create one-stage joint placement/rate actions plus an out option.

    Returned objects are ``OperatorDecision`` instances.  This function imports
    the CO2 well-placement types lazily so the matrix-analysis utilities can
    also be used without loading the flow solver.
    """
    try:
        from .co2_well_placement_game import OperatorDecision, WellPlacement, WellRate
    except ImportError:
        from co2_well_placement_game import OperatorDecision, WellPlacement, WellRate
    label = prefix or f"op{operator}"
    actions = [OperatorDecision()]
    seen = set()
    for k, (z, x) in enumerate(candidate_cells):
        cell = (int(z), int(x))
        if cell in seen:
            raise ValueError(f"duplicate candidate cell for operator {operator}: {cell}")
        seen.add(cell)
        for q in rates_m3_s:
            q = float(q)
            if not np.isfinite(q) or q <= 0:
                raise ValueError("placement actions require finite positive rates")
            wid = f"{label}-site{k}-z{cell[0]}-x{cell[1]}"
            actions.append(OperatorDecision(
                placements=(WellPlacement(wid, cell[0], cell[1], "injector"),),
                rates=(WellRate(wid, q),),
            ))
    return actions


def evaluate_solver_stage_game(
    game: Any,
    state: Any,
    geology: dict[str, np.ndarray],
    actions_by_operator: Sequence[Sequence[Any]],
    *,
    gravity_sign: int = 1,
) -> dict[str, Any]:
    """Exhaustively score the two-player action profile matrix with the CO2 solver.

    Use a one-stage config for a clean static game, or call this on a terminal
    state if the config accrues storage value only at the horizon.  Each profile
    receives a fresh deep copy of the same Markov state, so outcomes are paired
    counterfactuals.
    """
    from copy import deepcopy
    if len(actions_by_operator) != 2:
        raise ValueError("this exhaustive helper currently supports two operators")
    n0, n1 = len(actions_by_operator[0]), len(actions_by_operator[1])
    if not n0 or not n1:
        raise ValueError("each operator needs at least one action")
    payoffs = np.zeros((n0, n1, 2), dtype=np.float64)
    welfare = np.zeros((n0, n1), dtype=np.float64)
    pressure = np.zeros((n0, n1), dtype=np.float64)
    injected = np.zeros((n0, n1, 2), dtype=np.float64)
    dispatch = np.zeros((n0, n1, 2), dtype=np.float64)
    for i, action0 in enumerate(actions_by_operator[0]):
        for j, action1 in enumerate(actions_by_operator[1]):
            _, record = game.step(
                deepcopy(state), geology, (action0, action1), gravity_sign=gravity_sign
            )
            payoffs[i, j] = record["discounted_operator_payoff_by_operator"]
            welfare[i, j] = record["discounted_project_resource_welfare"]
            pressure[i, j] = record["pressure_max_pa"]
            injected[i, j] = record["storage_accepted_kg_by_operator"]
            dispatch[i, j] = record["pipeline_delivered_kg_by_operator"]
    analysis = analyze_bimatrix(payoffs)
    return {
        "payoffs": payoffs,
        "resource_welfare": welfare,
        "pressure_max_pa": pressure,
        "injected_kg_by_operator": injected,
        "pipeline_delivery_kg_by_operator": dispatch,
        "analysis": analysis,
        "action_counts": [n0, n1],
    }


def make_open_loop_two_stage_strategies(
    operator: int,
    candidate_cells: Sequence[tuple[int, int]],
    rates_m3_s: Sequence[float],
    *,
    allow_stage1_drill: bool = True,
) -> tuple[list[tuple[Any, Any]], list[str]]:
    """Enumerate two-stage well/rate schedules as pure strategies.

    A strategy commits to both stage decisions at the start. It is therefore
    an open-loop two-stage benchmark, useful for exhaustive Nash calculations,
    but it does not allow later actions to condition on an observed state.
    """
    try:
        from .co2_well_placement_game import OperatorDecision, WellPlacement, WellRate
    except ImportError:
        from co2_well_placement_game import OperatorDecision, WellPlacement, WellRate
    rates = tuple(float(x) for x in rates_m3_s)
    if len(rates) < 2 or any(not np.isfinite(x) or x <= 0 for x in rates):
        raise ValueError("rates_m3_s must contain at least two finite positive levels")
    low, high = rates[0], rates[-1]
    zero = OperatorDecision()
    strategies: list[tuple[Any, Any]] = [(zero, zero)]
    labels = ["out/out"]
    for k, cell0 in enumerate(candidate_cells):
        cell = (int(cell0[0]), int(cell0[1]))
        wid = f"op{operator}-2stage-site{k}-z{cell[0]}-x{cell[1]}"
        for q0, q0_label in ((low, "half"), (high, "full")):
            stage0 = OperatorDecision(
                placements=(WellPlacement(wid, cell[0], cell[1], "injector"),),
                rates=(WellRate(wid, q0),),
            )
            for q1, q1_label in ((0.0, "out"), (low, "half"), (high, "full")):
                stage1 = OperatorDecision(rates=(WellRate(wid, q1),))
                strategies.append((stage0, stage1))
                labels.append(f"{q0_label}@{cell}/ {q1_label}")
        if allow_stage1_drill:
            for q1, q1_label in ((low, "half"), (high, "full")):
                stage1 = OperatorDecision(
                    placements=(WellPlacement(wid, cell[0], cell[1], "injector"),),
                    rates=(WellRate(wid, q1),),
                )
                strategies.append((zero, stage1))
                labels.append(f"out / {q1_label}@{cell}")
    return strategies, labels


def evaluate_solver_open_loop_two_stage_game(
    game: Any,
    initial_state: Any,
    geology: dict[str, np.ndarray],
    strategies_by_operator: Sequence[Sequence[tuple[Any, Any]]],
) -> dict[str, Any]:
    """Exhaustively score two-stage open-loop schedules with the CO2 solver."""
    from copy import deepcopy
    if len(strategies_by_operator) != 2:
        raise ValueError("two-stage exhaustive helper currently supports two operators")
    if game.config.horizon != 2 or initial_state.stage != 0:
        raise ValueError("the open-loop helper requires a fresh two-stage game")
    n0, n1 = map(len, strategies_by_operator)
    payoffs = np.zeros((n0, n1, 2), dtype=np.float64)
    welfare = np.zeros((n0, n1), dtype=np.float64)
    pressure = np.zeros((n0, n1), dtype=np.float64)
    for i, s0 in enumerate(strategies_by_operator[0]):
        for j, s1 in enumerate(strategies_by_operator[1]):
            state = deepcopy(initial_state)
            pmax = 0.0
            for t in range(2):
                state, record = game.step(
                    state, geology, (s0[t], s1[t]))
                pmax = max(pmax, float(record["pressure_max_pa"]))
            payoffs[i, j] = state.core.cumulative_payoff_by_operator
            welfare[i, j] = float(state.core.cumulative_welfare)
            pressure[i, j] = pmax
    analysis = analyze_bimatrix(payoffs)
    return {"payoffs": payoffs, "resource_welfare": welfare,
            "pressure_max_pa": pressure, "analysis": analysis,
            "action_counts": [n0, n1],
            "solution_concept": "pure Nash of enumerated open-loop two-stage schedule game"}


def aggregate_geology_games(
    payoff_tensors: Sequence[np.ndarray],
    welfare_tensors: Sequence[np.ndarray] | None = None,
    *,
    risk_quantile: float = 0.10,
) -> dict[str, np.ndarray]:
    """Build expected-payoff and lower-tail robust games over matched geologies.

    ``risk_quantile=0.10`` yields cellwise 10th-percentile operator payoffs.
    The mean game is the primary expected-payoff case; the quantile game is a
    separately reported conservative sensitivity, not a posterior guarantee.
    """
    x = np.asarray(payoff_tensors, dtype=np.float64)
    if x.ndim != 4 or x.shape[-1] != 2 or x.shape[0] < 1:
        raise ValueError("payoff_tensors must have shape [geologies, a0, a1, 2]")
    if not 0 < risk_quantile < 1:
        raise ValueError("risk_quantile must lie strictly between 0 and 1")
    result = {"expected_payoffs": np.mean(x, axis=0),
              "lower_tail_payoffs": np.quantile(x, risk_quantile, axis=0),
              "geology_payoff_std": np.std(x, axis=0, ddof=1) if x.shape[0] > 1 else np.zeros_like(x[0])}
    if welfare_tensors is not None:
        w = np.asarray(welfare_tensors, dtype=np.float64)
        if w.shape != x.shape[:-1]:
            raise ValueError("welfare_tensors shape must match [geologies, a0, a1]")
        result["expected_welfare"] = np.mean(w, axis=0)
        result["lower_tail_welfare"] = np.quantile(w, risk_quantile, axis=0)
    return result


def load_co2_checkpoint(checkpoint: str, *, device: str = "cpu") -> dict[str, Any]:
    """Load a checkpoint using the CO2 trainer's own architecture and scaling."""
    import sys
    from pathlib import Path
    import torch
    try:
        from . import train_co2_xz_surrogate as trainer
    except ImportError:
        here = Path(__file__).resolve().parent
        if str(here) not in sys.path:
            sys.path.insert(0, str(here))
        import train_co2_xz_surrogate as trainer
    dev = torch.device(device)
    blob = torch.load(checkpoint, map_location=dev, weights_only=False)
    model = trainer.make_model(blob["backbone"], int(blob["width"]))
    model.load_state_dict(blob["state_dict"])
    model.to(dev).eval()
    stats = {k: np.asarray(v, dtype=np.float32) for k, v in blob["stats"].items()}
    return {"model": model, "stats": stats, "rate_scale": float(blob["rate_scale"]),
            "device": dev, "blob": blob, "trainer": trainer,
            "checkpoint": str(Path(checkpoint).resolve())}


def make_pressure_tail_unroll3_hybrid(
    pressure_checkpoint: str,
    dynamics_checkpoint: str,
    *,
    device: str = "cpu",
) -> dict[str, Any]:
    """Construct an unvalidated fieldwise CCS-GNN composition for ablation.

    Pressure delta comes from the pressure-tail model; mobile/trapped/max-gas
    and dissolved deltas come from the three-step-unroll model.  This is an
    experimental model composition, not a previously trained or proven winner.
    """
    pressure = load_co2_checkpoint(pressure_checkpoint, device=device)
    dynamics = load_co2_checkpoint(dynamics_checkpoint, device=device)
    if pressure["blob"]["backbone"] != "ccs_gnn" or dynamics["blob"]["backbone"] != "ccs_gnn":
        raise ValueError("this composition expects two CCS-GNN checkpoints")
    for key in ("rate_scale",):
        if not np.isclose(pressure[key], dynamics[key], rtol=0, atol=1e-12):
            raise ValueError(f"paired checkpoints disagree on {key}")
    for key in ("x_mean", "x_std", "y_mean", "y_std"):
        if not np.allclose(pressure["stats"][key], dynamics["stats"][key],
                           rtol=0, atol=1e-7):
            raise ValueError(f"paired checkpoints disagree on normalization {key}")
    def predict_delta(data: dict[str, np.ndarray], dynamic: dict[str, np.ndarray]) -> np.ndarray:
        dp = pressure["trainer"].predict_delta(
            pressure["model"], data, pressure["stats"], pressure["rate_scale"],
            pressure["device"], batch=1, dynamic=dynamic)
        dd = dynamics["trainer"].predict_delta(
            dynamics["model"], data, dynamics["stats"], dynamics["rate_scale"],
            dynamics["device"], batch=1, dynamic=dynamic)
        hybrid = dd.copy()
        hybrid[:, 0] = dp[:, 0]
        return hybrid
    return {"model": None, "stats": dynamics["stats"],
            "rate_scale": dynamics["rate_scale"], "device": dynamics["device"],
            "blob": {"backbone": "ccs_gnn_pressure_tail+unroll3", "seed": None},
            "trainer": dynamics["trainer"], "checkpoint":
                f"{pressure['checkpoint']}|{dynamics['checkpoint']}",
            "predict_delta_fn": predict_delta,
            "surrogate_components": {
                "pressure": pressure["checkpoint"],
                "other_state_fields": dynamics["checkpoint"]}}


def evaluate_surrogate_stage_game(
    game: Any,
    state: Any,
    geology: dict[str, np.ndarray],
    actions_by_operator: Sequence[Sequence[Any]],
    surrogate: dict[str, Any],
    *,
    dx_ft: float,
    dy_ft: float,
    dz_ft: float,
    gravity_sign: int = 1,
) -> dict[str, Any]:
    """Score a stage game with a CO2 surrogate, returning a forecast payoff table.

    **Scope guard:** this function only supports the trainer's fixed two-well
    feature map at ``z=h-2, x≈w/3`` and ``z=h-2, x≈2w/3``.  The current training
    data encode well locations at those two cells; arbitrary well-placement
    actions are out of distribution and are rejected.  Use the solver scorer
    for placement search until a location-randomized CO2 dataset/checkpoint is
    trained.
    """
    from copy import deepcopy
    try:
        from .co2_pipeline_game import dispatch_mass
    except ImportError:
        from co2_pipeline_game import dispatch_mass
    if len(actions_by_operator) != 2:
        raise ValueError("current CO2 checkpoint input has exactly two operator rate channels")
    cfg = game.config
    if state.stage + 1 != cfg.horizon:
        raise ValueError("surrogate payoff scoring currently requires a terminal one-stage game")
    kx = np.asarray(geology["kx_mD"], dtype=np.float32)
    kz = np.asarray(geology["kz_mD"], dtype=np.float32)
    phi = np.asarray(geology["phi"], dtype=np.float32)
    if kx.ndim != 2 or kz.shape != kx.shape or phi.shape != kx.shape:
        raise ValueError("geology arrays must be matching [z,x] grids")
    h, w = kx.shape
    z_well = h - 2
    x_wells = (max(1, w // 3), min(w - 2, (2 * w) // 3))
    dyn0 = state.core.reservoir
    for owner, action_set in enumerate(actions_by_operator):
        for action in action_set:
            cells = {(int(p.z_index), int(p.x_index)) for p in action.placements
                     if p.well_type == "injector"}
            rates = {str(r.well_id): float(r.rate_m3_s) for r in action.rates}
            if len(cells) > 1 or (cells and next(iter(cells)) != (z_well, x_wells[owner])):
                raise ValueError("surrogate rate-game actions must use its trained fixed well cells")
            if action.placements and len(rates) != 1:
                raise ValueError("surrogate rate-game supports at most one injector per operator")
    n0, n1 = len(actions_by_operator[0]), len(actions_by_operator[1])
    payoffs = np.zeros((n0, n1, 2), dtype=np.float64)
    welfare = np.zeros((n0, n1), dtype=np.float64)
    pressure = np.zeros((n0, n1), dtype=np.float64)
    predicted_states: dict[tuple[int, int], dict[str, np.ndarray]] = {}
    trainer = surrogate["trainer"]
    rho = float(game.solver.cfg.rho_co2_kg_m3)
    for i, a0 in enumerate(actions_by_operator[0]):
        for j, a1 in enumerate(actions_by_operator[1]):
            acts = (a0, a1)
            requested_rate = np.asarray([
                sum(float(r.rate_m3_s) for r in a.rates) for a in acts
            ], dtype=np.float64)
            requested_mass = requested_rate * cfg.stage_duration_s * rho
            cap = cfg.pipeline.available_mass_kg_per_stage
            delivered = dispatch_mass(requested_mass, cap, cfg.pipeline.dispatch_rule)
            if cfg.storage_cap_kg is not None:
                remaining = max(0.0, cfg.storage_cap_kg
                                - float(state.core.cumulative_injected_kg_by_operator.sum()))
                if cfg.storage_dispatch_rule == "fixed_equal":
                    quota = np.maximum(cfg.storage_cap_kg / 2
                                       - state.core.cumulative_injected_kg_by_operator, 0.0)
                    delivered = np.minimum(delivered, quota)
                else:
                    delivered = dispatch_mass(delivered, remaining, cfg.storage_dispatch_rule)
            realized_rates = delivered / (cfg.stage_duration_s * rho)
            data = {
                "kx_mD": kx[None], "kz_mD": kz[None], "phi": phi[None],
                "rate_operator_0_m3_s": np.asarray([realized_rates[0]], np.float32),
                "rate_operator_1_m3_s": np.asarray([realized_rates[1]], np.float32),
                "dx_ft": np.asarray([dx_ft], np.float32),
                "dy_ft": np.asarray([dy_ft], np.float32),
                "dz_ft": np.asarray([dz_ft], np.float32),
            }
            dynamic = {key: np.asarray(dyn0[key], dtype=np.float32)[None]
                       for key in trainer.STATE_KEYS}
            if surrogate.get("predict_delta_fn") is not None:
                delta = surrogate["predict_delta_fn"](data, dynamic)
            else:
                delta = trainer.predict_delta(
                    surrogate["model"], data, surrogate["stats"], surrogate["rate_scale"],
                    surrogate["device"], batch=1, dynamic=dynamic)
            pred = trainer._to_states(data, delta, dynamic=dynamic)
            predicted_states[(i, j)] = pred
            pmax = float(np.max(pred["p_pa"]))
            pressure[i, j] = pmax
            costs = delivered * cfg.pipeline.resource_cost_per_kg
            tariffs = delivered * cfg.pipeline.tariff_per_kg
            drill = np.asarray([len(a.placements) for a in acts], dtype=np.float64)
            drill_cost = drill * cfg.payoff.drilling_cost_per_well
            exceed = max(0.0, pmax - float(cfg.payoff.pressure_cap_pa or 0.0))
            pressure_cost = cfg.payoff.pressure_damage_per_pa2 * exceed ** 2
            liability = delivered / delivered.sum() if delivered.sum() > 0 else np.zeros(2)
            damage_alloc = pressure_cost * liability
            storage = (state.core.cumulative_injected_kg_by_operator + delivered) \
                * cfg.payoff.storage_value_per_kg
            value = storage - costs - tariffs - drill_cost - damage_alloc
            factor = cfg.discount_factor ** state.stage
            payoffs[i, j] = value * factor
            welfare[i, j] = float((storage.sum() - costs.sum() - tariffs.sum()
                                   - drill_cost.sum() - pressure_cost) * factor)
    analysis = analyze_bimatrix(payoffs)
    return {"payoffs": payoffs, "resource_welfare": welfare,
            "pressure_max_pa": pressure, "analysis": analysis,
            "predicted_states": predicted_states,
            "action_counts": [n0, n1],
            "checkpoint": surrogate["checkpoint"],
            "checkpoint_backbone": surrogate["blob"]["backbone"],
            "checkpoint_seed": surrogate["blob"].get("seed"),
            "surrogate_scope": "fixed trained injection cells; one-stage transition"}


def compare_planner_to_solver(
    solver_payoffs: np.ndarray,
    planner_payoffs: np.ndarray,
    *,
    action_labels: Sequence[Sequence[str]] | None = None,
    solver_pressure_pa: np.ndarray | None = None,
) -> dict[str, Any]:
    """Measure how a model-selected equilibrium behaves under solver payoffs."""
    u = np.asarray(solver_payoffs, dtype=np.float64)
    v = np.asarray(planner_payoffs, dtype=np.float64)
    if u.shape != v.shape or u.ndim != 3 or u.shape[-1] != 2:
        raise ValueError("solver and planner payoffs must share shape [a0,a1,2]")
    predicted = analyze_bimatrix(v)
    truth = analyze_bimatrix(u)
    selected = predicted.pure_nash_profiles
    if not selected:
        # If the planner's finite game has no pure NE, evaluate all profiles
        # with the highest planner welfare and flag that this is a fallback.
        social = analyze_bimatrix(v).welfare_maximizers
        selected = social
        selection_rule = "planner_welfare_fallback_no_pure_NE"
    else:
        selection_rule = "planner_pure_Nash_profiles"
    items = []
    for i, j in selected:
        regret = truth.nash_regret[i, j]
        item = {"profile": [i, j], "solver_payoff_by_operator": u[i, j].tolist(),
                "solver_regret_by_operator": regret.tolist(),
                "solver_epsilon_sum": float(regret.sum()),
                "solver_welfare": float(truth.welfare[i, j])}
        if solver_pressure_pa is not None:
            p = np.asarray(solver_pressure_pa, dtype=np.float64)
            if p.shape != u.shape[:2]:
                raise ValueError("solver_pressure_pa must have shape [a0,a1]")
            item["solver_pressure_max_pa"] = float(p[i, j])
        if action_labels is not None:
            item["action_labels"] = [action_labels[0][i], action_labels[1][j]]
        items.append(item)
    return {"selection_rule": selection_rule,
            "planner_pure_nash_profiles": [list(x) for x in predicted.pure_nash_profiles],
            "solver_pure_nash_profiles": [list(x) for x in truth.pure_nash_profiles],
            "planner_selected_solver_replays": items}


@dataclass(frozen=True)
class GameAnalysis:
    pure_nash_profiles: tuple[tuple[int, int], ...]
    welfare_maximizers: tuple[tuple[int, int], ...]
    nash_regret: np.ndarray
    welfare: np.ndarray


def analyze_bimatrix(payoffs: np.ndarray, *, atol: float = 1e-9) -> GameAnalysis:
    """Find all pure Nash profiles, unilateral regrets, and welfare optima."""
    u = np.asarray(payoffs, dtype=np.float64)
    if u.ndim != 3 or u.shape[2] != 2 or min(u.shape[:2]) < 1:
        raise ValueError("payoffs must have shape [actions_op0, actions_op1, 2]")
    if not np.all(np.isfinite(u)):
        raise ValueError("payoffs contain non-finite entries")
    best0 = np.max(u[:, :, 0], axis=0, keepdims=True)
    best1 = np.max(u[:, :, 1], axis=1, keepdims=True)
    regret0 = np.maximum(0.0, best0 - u[:, :, 0])
    regret1 = np.maximum(0.0, best1 - u[:, :, 1])
    regret = np.stack((regret0, regret1), axis=-1)
    pure = tuple((int(i), int(j)) for i, j in np.argwhere(
        np.all(regret <= atol, axis=-1)))
    welfare = np.sum(u, axis=-1)
    max_welfare = float(np.max(welfare))
    social = tuple((int(i), int(j)) for i, j in np.argwhere(
        welfare >= max_welfare - atol))
    return GameAnalysis(pure, social, regret, welfare)


def _choose_best(values: np.ndarray, rng: np.random.Generator,
                 tie_break: str, atol: float) -> int:
    best = np.max(values)
    choices = np.flatnonzero(values >= best - atol)
    if tie_break == "first":
        return int(choices[0])
    if tie_break == "random":
        return int(rng.choice(choices))
    if tie_break == "stay":
        raise ValueError("stay tie-breaking needs a current action")
    raise ValueError("tie_break must be 'first', 'random', or 'stay'")


def best_response_dynamics(
    payoffs: np.ndarray,
    *,
    starts: int = 100,
    max_rounds: int = 200,
    update: str = "alternating",
    tie_break: str = "random",
    seed: int = 0,
    atol: float = 1e-9,
) -> list[dict[str, Any]]:
    """Run multi-start best-response paths and record convergence or cycles.

    ``update='alternating'`` updates one randomly selected player per round;
    ``simultaneous'`` updates both against the previous-round action.  A path
    is marked converged only when it reaches an exact pure Nash profile.
    """
    u = np.asarray(payoffs, dtype=np.float64)
    if u.ndim != 3 or u.shape[2] != 2:
        raise ValueError("payoffs must have shape [n0, n1, 2]")
    if starts < 1 or max_rounds < 1:
        raise ValueError("starts and max_rounds must be positive")
    if update not in {"alternating", "simultaneous"}:
        raise ValueError("update must be 'alternating' or 'simultaneous'")
    rng = np.random.default_rng(seed)
    eq = set(analyze_bimatrix(u, atol=atol).pure_nash_profiles)
    paths = []
    for run in range(starts):
        a = [int(rng.integers(u.shape[0])), int(rng.integers(u.shape[1]))]
        history = [tuple(a)]
        seen = {tuple(a): 0}
        outcome = "max_rounds"
        for round_i in range(1, max_rounds + 1):
            old = tuple(a)
            if update == "simultaneous":
                next_a = [
                    _choose_best(u[:, old[1], 0], rng, tie_break, atol),
                    _choose_best(u[old[0], :, 1], rng, tie_break, atol),
                ]
            else:
                player = int(rng.integers(2))
                if player == 0:
                    a[0] = _choose_best(u[:, a[1], 0], rng, tie_break, atol)
                else:
                    a[1] = _choose_best(u[a[0], :, 1], rng, tie_break, atol)
                next_a = a
            a = list(next_a)
            profile = tuple(a)
            history.append(profile)
            if profile in eq:
                outcome = "pure_nash"
                break
            if profile in seen:
                outcome = "cycle"
                break
            seen[profile] = round_i
        paths.append({"run": run, "start": history[0], "path": history,
                      "outcome": outcome, "rounds": len(history) - 1,
                      "terminal": history[-1]})
    return paths


def fictitious_play(
    payoffs: np.ndarray,
    *,
    steps: int = 5000,
    starts: int = 20,
    seed: int = 0,
    tie_break: str = "random",
    atol: float = 1e-9,
) -> list[dict[str, Any]]:
    """Run empirical-frequency fictitious play with average exploitability."""
    u = np.asarray(payoffs, dtype=np.float64)
    if u.ndim != 3 or u.shape[2] != 2:
        raise ValueError("payoffs must have shape [n0, n1, 2]")
    rng = np.random.default_rng(seed)
    out = []
    for run in range(starts):
        n0, n1 = u.shape[:2]
        counts0 = np.zeros(n0, dtype=np.float64)
        counts1 = np.zeros(n1, dtype=np.float64)
        a0, a1 = int(rng.integers(n0)), int(rng.integers(n1))
        records = []
        for t in range(1, steps + 1):
            counts0[a0] += 1.0
            counts1[a1] += 1.0
            q0 = counts0 / counts0.sum()
            q1 = counts1 / counts1.sum()
            # Simultaneous response to the opponent's empirical distribution.
            a0 = _choose_best(u[:, :, 0] @ q1, rng, tie_break, atol)
            a1 = _choose_best(q0 @ u[:, :, 1], rng, tie_break, atol)
            if t == 1 or t % max(1, steps // 50) == 0 or t == steps:
                br0 = float(np.max(u[:, :, 0] @ q1) - q0 @ u[:, :, 0] @ q1)
                br1 = float(np.max(q0 @ u[:, :, 1]) - q0 @ u[:, :, 1] @ q1)
                records.append({"step": t, "exploitability_sum": br0 + br1,
                                "exploitability_by_player": [br0, br1],
                                "mix_op0": q0.tolist(), "mix_op1": q1.tolist()})
        out.append({"run": run, "trace": records,
                    "final_exploitability": records[-1]["exploitability_sum"]})
    return out


def logit_response_dynamics(
    payoffs: np.ndarray,
    *,
    temperatures: Sequence[float] = (1.0, 0.3, 0.1, 0.03),
    steps: int = 5000,
    seed: int = 0,
    atol: float = 1e-9,
) -> list[dict[str, Any]]:
    """Simulate noisy response at several temperatures and report exploitability.

    This is a behavioral convergence experiment.  Low temperature approximates
    best response; it is not a guarantee of Nash convergence.
    """
    u = np.asarray(payoffs, dtype=np.float64)
    if u.ndim != 3 or u.shape[2] != 2:
        raise ValueError("payoffs must have shape [n0, n1, 2]")
    rng = np.random.default_rng(seed)

    def softmax(x: np.ndarray, tau: float) -> np.ndarray:
        y = (x - np.max(x)) / tau
        z = np.exp(np.clip(y, -700, 0))
        return z / z.sum()

    results = []
    for tau in temperatures:
        if not np.isfinite(tau) or tau <= 0:
            raise ValueError("temperatures must be finite and positive")
        p0 = np.full(u.shape[0], 1.0 / u.shape[0])
        p1 = np.full(u.shape[1], 1.0 / u.shape[1])
        trace = []
        for t in range(1, steps + 1):
            target0 = softmax(u[:, :, 0] @ p1, float(tau))
            target1 = softmax(p0 @ u[:, :, 1], float(tau))
            # Damped updates avoid confusing oscillation from synchronous
            # discrete best-response with convergence of mixed strategies.
            p0 = 0.9 * p0 + 0.1 * target0
            p1 = 0.9 * p1 + 0.1 * target1
            if t == 1 or t % max(1, steps // 50) == 0 or t == steps:
                r0 = float(np.max(u[:, :, 0] @ p1) - p0 @ u[:, :, 0] @ p1)
                r1 = float(np.max(p0 @ u[:, :, 1]) - p0 @ u[:, :, 1] @ p1)
                trace.append({"step": t, "exploitability_sum": r0 + r1,
                              "exploitability_by_player": [r0, r1],
                              "mix_op0": p0.tolist(), "mix_op1": p1.tolist()})
        results.append({"temperature": float(tau), "trace": trace,
                        "final_exploitability": trace[-1]["exploitability_sum"]})
    return results


def summarize_dynamics(paths: Sequence[dict[str, Any]]) -> dict[str, Any]:
    """Summarize pure best-response convergence and cycle frequencies."""
    n = max(len(paths), 1)
    counts = {key: sum(p["outcome"] == key for p in paths)
              for key in ("pure_nash", "cycle", "max_rounds")}
    conv = [p["rounds"] for p in paths if p["outcome"] == "pure_nash"]
    return {"n_starts": len(paths), **{f"{k}_count": v for k, v in counts.items()},
            "pure_nash_convergence_fraction": counts["pure_nash"] / n,
            "median_rounds_if_converged": float(np.median(conv)) if conv else None}
